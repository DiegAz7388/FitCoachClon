-- FitCoach · App móvil de pacientes
-- Agrega lo necesario para que un paciente inicie sesión, vea SU rutina,
-- registre entrenamientos y medidas, y para guardar animaciones y tiempos.
-- Es aditiva: no borra columnas ni políticas existentes. Revísala antes de aplicarla.

-- 1) Vincular expediente con la cuenta del paciente -------------------------
alter table public.fc_clients add column if not exists user_id uuid unique references auth.users(id) on delete set null;

-- 2) Catálogo: animación, imagen y equipo ----------------------------------
alter table public.fc_exercises add column if not exists catalog_id text;
alter table public.fc_exercises add column if not exists gif_url text;
alter table public.fc_exercises add column if not exists image_url text;
alter table public.fc_exercises add column if not exists equipment text;
alter table public.fc_exercises add column if not exists category text;

-- 3) Ejercicios por tiempo (p. ej. plancha 45 s) y notas -------------------
alter table public.fc_routine_exercises add column if not exists duration_seconds integer check (duration_seconds is null or duration_seconds > 0);
alter table public.fc_routine_exercises add column if not exists notes text;

-- 4) Entrenamientos realizados ---------------------------------------------
create table if not exists public.fc_workout_sessions (
  id bigint generated by default as identity primary key,
  client_id bigint not null references public.fc_clients(id) on delete cascade,
  routine_id bigint references public.fc_routines(id) on delete set null,
  day_of_week smallint,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  duration_seconds integer,
  total_volume_kg numeric(10,2) default 0,
  notes text
);
create index if not exists fc_workout_sessions_client_idx on public.fc_workout_sessions (client_id, started_at desc);

create table if not exists public.fc_set_logs (
  id bigint generated by default as identity primary key,
  session_id bigint not null references public.fc_workout_sessions(id) on delete cascade,
  exercise_id bigint references public.fc_exercises(id) on delete set null,
  exercise_name text not null,
  set_number smallint not null,
  reps smallint,
  weight_kg numeric(6,2),
  duration_seconds integer,
  completed_at timestamptz not null default now()
);
create index if not exists fc_set_logs_session_idx on public.fc_set_logs (session_id);

-- 5) Medidas corporales (peso, % grasa, cintura) ---------------------------
create table if not exists public.fc_body_measurements (
  id bigint generated by default as identity primary key,
  client_id bigint not null references public.fc_clients(id) on delete cascade,
  measured_at date not null default current_date,
  weight_kg numeric(5,2),
  body_fat_pct numeric(4,1),
  waist_cm numeric(5,1),
  notes text,
  created_by uuid default auth.uid()
);
create index if not exists fc_body_measurements_client_idx on public.fc_body_measurements (client_id, measured_at);

-- 6) Funciones auxiliares ---------------------------------------------------
-- Expediente del usuario que hace la consulta (null si no es paciente).
create or replace function public.fc_current_client_id()
returns bigint language sql stable security definer set search_path = public as $$
  select id from public.fc_clients where user_id = auth.uid() limit 1
$$;

-- El paciente reclama su expediente: el nutriólogo lo registró con el mismo correo.
create or replace function public.fc_claim_client()
returns bigint language plpgsql security definer set search_path = public as $$
declare claimed bigint;
begin
  select id into claimed from public.fc_clients where user_id = auth.uid() limit 1;
  if claimed is not null then return claimed; end if;
  update public.fc_clients set user_id = auth.uid()
   where id = (select id from public.fc_clients
                where user_id is null and lower(email) = lower(auth.jwt() ->> 'email')
                order by created_at desc limit 1)
  returning id into claimed;
  return claimed;
end $$;
revoke all on function public.fc_claim_client() from public, anon;
grant execute on function public.fc_claim_client() to authenticated;
grant execute on function public.fc_current_client_id() to authenticated;

-- 7) RLS para pacientes (se suman a las políticas de admin/trainer) --------
alter table public.fc_workout_sessions enable row level security;
alter table public.fc_set_logs enable row level security;
alter table public.fc_body_measurements enable row level security;

drop policy if exists "paciente lee su expediente" on public.fc_clients;
create policy "paciente lee su expediente" on public.fc_clients for select to authenticated
  using (user_id = auth.uid());

drop policy if exists "paciente lee sus rutinas" on public.fc_routines;
create policy "paciente lee sus rutinas" on public.fc_routines for select to authenticated
  using (client_id = public.fc_current_client_id());

drop policy if exists "paciente lee sus días" on public.fc_routine_days;
create policy "paciente lee sus días" on public.fc_routine_days for select to authenticated
  using (routine_id in (select id from public.fc_routines where client_id = public.fc_current_client_id()));

drop policy if exists "paciente lee sus ejercicios" on public.fc_routine_exercises;
create policy "paciente lee sus ejercicios" on public.fc_routine_exercises for select to authenticated
  using (routine_id in (select id from public.fc_routines where client_id = public.fc_current_client_id()));

drop policy if exists "catálogo visible" on public.fc_exercises;
create policy "catálogo visible" on public.fc_exercises for select to authenticated using (true);

-- Sesiones, series y medidas: el paciente maneja las suyas; el entrenador del paciente las consulta.
drop policy if exists "paciente sus sesiones" on public.fc_workout_sessions;
create policy "paciente sus sesiones" on public.fc_workout_sessions for all to authenticated
  using (client_id = public.fc_current_client_id()) with check (client_id = public.fc_current_client_id());
drop policy if exists "entrenador ve sesiones" on public.fc_workout_sessions;
create policy "entrenador ve sesiones" on public.fc_workout_sessions for select to authenticated
  using (client_id in (select id from public.fc_clients where trainer_id = auth.uid()));

drop policy if exists "paciente sus series" on public.fc_set_logs;
create policy "paciente sus series" on public.fc_set_logs for all to authenticated
  using (session_id in (select id from public.fc_workout_sessions where client_id = public.fc_current_client_id()))
  with check (session_id in (select id from public.fc_workout_sessions where client_id = public.fc_current_client_id()));
drop policy if exists "entrenador ve series" on public.fc_set_logs;
create policy "entrenador ve series" on public.fc_set_logs for select to authenticated
  using (session_id in (select s.id from public.fc_workout_sessions s join public.fc_clients c on c.id = s.client_id where c.trainer_id = auth.uid()));

drop policy if exists "paciente sus medidas" on public.fc_body_measurements;
create policy "paciente sus medidas" on public.fc_body_measurements for all to authenticated
  using (client_id = public.fc_current_client_id()) with check (client_id = public.fc_current_client_id());
drop policy if exists "entrenador sus pacientes medidas" on public.fc_body_measurements;
create policy "entrenador sus pacientes medidas" on public.fc_body_measurements for all to authenticated
  using (client_id in (select id from public.fc_clients where trainer_id = auth.uid()))
  with check (client_id in (select id from public.fc_clients where trainer_id = auth.uid()));
